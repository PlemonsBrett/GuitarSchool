/**
 * One-time generator for supabase/migrations/*_seed_catalog.sql from the initial curriculum in this folder.
 * After the seed migration is applied, the database is the source of truth and /admin edits it.
 *
 *   pnpm seed:generate
 */
import { writeFileSync } from 'node:fs'
import { chords } from './chords'
import { electricLead } from './electric-lead'
import type { Track } from './types'

const q = (s: string) => `'${s.replace(/'/g, "''")}'`
const qn = (s?: string | null) => (s == null ? 'null' : q(s))
const arr = (xs: string[]) => (xs.length ? `array[${xs.map(q).join(', ')}]::text[]` : `'{}'::text[]`)
const ints = (xs: number[]) => `array[${xs.join(', ')}]::int[]`

const lines: string[] = ['-- Generated by scripts/seed/generate.ts. Initial catalog; edit content in /admin afterwards.', '']

lines.push('insert into public.chords (id, name, frets, fingers, barre) values')
lines.push(
  Object.entries(chords)
    .map(([id, c]) => {
      const barre = 'barre' in c && c.barre ? `${q(JSON.stringify(c.barre))}::jsonb` : 'null'
      return `  (${q(id)}, ${q(c.name)}, ${ints(c.frets)}, ${ints(c.fingers)}, ${barre})`
    })
    .join(',\n') + '\non conflict (id) do nothing;',
)
lines.push('')

type Stub = { slug: string; path: 'acoustic' | 'electric'; style: string; title: string; blurb: string }
const stubs: Stub[] = [
  { slug: 'electric-rhythm', path: 'electric', style: 'Rhythm', title: 'Electric Rhythm', blurb: 'Chords, grooves, palm muting.' },
  { slug: 'acoustic-traditional', path: 'acoustic', style: 'Traditional', title: 'Acoustic Traditional', blurb: 'Strumming and flatpicking.' },
  { slug: 'acoustic-fingerstyle', path: 'acoustic', style: 'Fingerstyle', title: 'Acoustic Fingerstyle', blurb: 'Pattern picking and arrangements.' },
]

function track(t: Track, position: number) {
  lines.push(
    `insert into public.tracks (slug, path, style, title, blurb, tagline, status, position, warmup_slug, habits, graduation) values`,
    `  (${q(t.slug)}, ${q(t.path)}, ${q(t.style)}, ${q(t.title)}, ${q('Scales, bends, solos.')}, ${q(t.tagline)}, 'published', ${position}, 'spider', ${arr(t.habits)}, ${arr(t.graduation)})`,
    `on conflict (slug) do nothing;`,
    '',
  )
  t.phases.forEach((p, pi) => {
    lines.push(
      `insert into public.phases (track_slug, slug, position, title, months, summary, milestone_slug, milestone_text) values`,
      `  (${q(t.slug)}, ${q(p.slug)}, ${pi}, ${q(p.title)}, ${q(p.months)}, ${q(p.summary)}, ${q(p.milestone.slug)}, ${q(p.milestone.text)})`,
      `on conflict (track_slug, slug) do nothing;`,
    )
    p.items.forEach((it, ii) => {
      lines.push(
        `insert into public.items (track_slug, phase_id, slug, position, kind, title, detail, query, chords, chord_note)`,
        `select ${q(t.slug)}, ph.id, ${q(it.slug)}, ${ii}, ${q(it.kind)}, ${q(it.title)}, ${q(it.detail)}, ${qn(it.query)}, ${arr(it.media?.chords ?? [])}, ${qn(it.media?.chordNote)}`,
        `from public.phases ph where ph.track_slug = ${q(t.slug)} and ph.slug = ${q(p.slug)}`,
        `on conflict (track_slug, slug) do nothing;`,
      )
      ;(it.media?.notation ?? []).forEach((n, ni) => {
        // $tex$ quoting keeps backslashes and newlines in alphaTex exactly as written.
        lines.push(
          `insert into public.notations (item_id, position, title, caption, format, tex)`,
          `select i.id, ${ni}, ${q(n.title)}, ${qn(n.caption)}, 'alphatex', $tex$${n.tex}$tex$`,
          `from public.items i where i.track_slug = ${q(t.slug)} and i.slug = ${q(it.slug)}`,
          `and not exists (select 1 from public.notations x where x.item_id = i.id and x.title = ${q(n.title)});`,
        )
      })
    })
    lines.push('')
  })
}

track(electricLead, 0)
lines.push(
  'insert into public.tracks (slug, path, style, title, blurb, status, position) values',
  stubs.map((s, i) => `  (${q(s.slug)}, ${q(s.path)}, ${q(s.style)}, ${q(s.title)}, ${q(s.blurb)}, 'coming_soon', ${i + 1})`).join(',\n'),
  'on conflict (slug) do nothing;',
  '',
)

const out = new URL('../../supabase/migrations/20261115000200_seed_catalog.sql', import.meta.url)
writeFileSync(out, lines.join('\n'))
console.log('wrote', out.pathname)
